_CONSTRAINT_RE = re.compile(r"\s+(PRIMARY\s+KEY|NOT\s+NULL|UNIQUE)\b", re.IGNORECASE)


def column_name(definition: str) -> str:
    """The column a definition declares, unquoted: ``'"rows" BIGINT'`` -> ``rows``."""
    return definition.split(None, 1)[0].strip('"')


def column_definition(table: Table, definition: str, is_lake: bool) -> str:
    """A column definition as CREATE TABLE takes it on this backend."""
    if is_lake:
        definition = table.lake_columns.get(column_name(definition), definition)
        definition = re.sub(r"\s+(PRIMARY\s+KEY|UNIQUE)\b", "", definition, flags=re.IGNORECASE)
    return definition


def added_column_definition(table: Table, definition: str, is_lake: bool) -> str:
    """A column definition as ``ALTER TABLE ... ADD COLUMN`` takes it.

    Constraints are dropped: an existing table's rows have no value for the
    new column, so NOT NULL could not hold, and DuckDB cannot add a key to a
    table that has rows. The DEFAULT stays, so new rows get it.
    """
    return _CONSTRAINT_RE.sub("", column_definition(table, definition, is_lake))


def create_statement(table: Table, is_lake: bool) -> str:
    parts = [column_definition(table, c, is_lake) for c in table.columns]
    if not is_lake:
        parts.extend(table.constraints)
    body = ",\n    ".join(parts)
    return f"CREATE TABLE IF NOT EXISTS _havn.{table.name} (\n    {body}\n)"


def existing_columns(conn: duckdb.DuckDBPyConnection) -> dict[str, set[str]]:
    """``{table: {column, ...}}`` for every table in ``_havn`` of the current database."""
    rows = conn.execute(
        "SELECT table_name, column_name FROM duckdb_columns() "
        "WHERE database_name = current_database() AND schema_name = '_havn'"
    ).fetchall()
    present: dict[str, set[str]] = {}
    for table, column in rows:
        present.setdefault(str(table), set()).add(str(column))
    return present


