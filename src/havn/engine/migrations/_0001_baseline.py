"""Migration 1: the baseline ``_havn`` schema.

Releases up to 0.3.1 created these tables lazily, each from its own
``ensure_*`` function, and evolved them with ``ALTER TABLE ... ADD COLUMN IF
NOT EXISTS`` wrapped in ``try/except``. A warehouse written by any of those
releases can therefore hold any subset of the tables below, and a table that
does exist may lack columns added later (see ``ADDED_AFTER_FIRST_RELEASE``).

This migration brings every such warehouse, and an empty one, to the same
schema without relying on swallowed errors: a missing table is created whole,
and for a table that exists each column is looked up in the catalog and only
the missing ones are added. Nothing is dropped, renamed or retyped, so rows
written by an older release are kept as they are.

Do not edit this file to change the schema after it has shipped: a warehouse
already at version 1 would never see the change. Add a new migration instead.
"""

